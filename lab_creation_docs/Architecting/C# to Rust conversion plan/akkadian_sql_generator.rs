#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_simple_hub() {
        let mut program = AkkadianProgram::new();
        let mut context = ContextNode::new("TestContext".to_string());
        
        let mut storage = StorageNode::new();
        let mut hub = TableNode::new("PersonHub".to_string(), TableType::Hub);
        
        hub.columns.push(ColumnNode {
            name: "id".to_string(),
            data_type: "UUID".to_string(),
            is_primary_key: true,
            is_unique: false,
        });
        
        hub.columns.push(ColumnNode {
            name: "name".to_string(),
            data_type: "VARCHAR(100)".to_string(),
            is_primary_key: false,
            is_unique: false,
        });
        
        storage.hubs.push(hub);
        context.storage = Some(storage);
        program.contexts.push(context);
        
        let sql = SqlGenerator::generate(&program).unwrap();
        
        assert!(sql.contains("CREATE SCHEMA IF NOT EXISTS TestContext"));
        assert!(sql.contains("CREATE TABLE IF NOT EXISTS TestContext.PersonHub"));
        assert!(sql.contains("id UUID PRIMARY KEY"));
        assert!(sql.contains("name VARCHAR(100)"));
        assert!(sql.contains("LoadDate TIMESTAMP"));
        assert!(sql.contains("RecordSource VARCHAR(100)"));
    }

    #[test]
    fn test_generate_temporal_satellite() {
        let mut program = AkkadianProgram::new();
        let mut context = ContextNode::new("Test".to_string());
        
        let mut storage = StorageNode::new();
        let mut sat = TableNode::new("PersonDetails".to_string(), TableType::Satellite);
        sat.has_temporal_tracking = true;
        
        sat.columns.push(ColumnNode {
            name: "person_id".to_string(),
            data_type: "UUID".to_string(),
            is_primary_key: true,
            is_unique: false,
        });
        
        storage.satellites.push(sat);
        context.storage = Some(storage);
        program.contexts.push(context);
        
        let sql = SqlGenerator::generate(&program).unwrap();
        
        assert!(sql.contains("ValidFrom TIMESTAMP"));
        assert!(sql.contains("ValidTo TIMESTAMP"));
        assert!(sql.contains("IsCurrent BOOLEAN"));
    }

    #[test]
    fn test_type_mapping() {
        assert_eq!(SqlGenerator::map_to_postgres_type("UUID"), "UUID");
        assert_eq!(SqlGenerator::map_to_postgres_type("INT"), "INTEGER");
        assert_eq!(SqlGenerator::map_to_postgres_type("BIGINT"), "BIGINT");
        assert_eq!(SqlGenerator::map_to_postgres_type("VARCHAR(100)"), "VARCHAR(100)");
    }
}
